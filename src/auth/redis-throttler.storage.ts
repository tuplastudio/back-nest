import { Logger } from '@nestjs/common';
import { connect as netConnect, type Socket } from 'node:net';
import { connect as tlsConnect } from 'node:tls';
import type { ThrottlerStorage } from '@nestjs/throttler';

/**
 * Shared rate-limit storage on Redis / Memorystore (BN-REQ-SEC-004).
 *
 * The in-memory default counts per instance, so with N Cloud Run instances an
 * attacker gets N times the sign-in budget. Enabled only when
 * `THROTTLER_REDIS_URL` is set; nothing here provisions Redis.
 *
 * Zero dependencies on purpose: the throttler needs a single `EVAL`, which a
 * few dozen lines of RESP framing cover, instead of a client library and its
 * supply chain.
 */

/** Reply shape `ThrottlerStorage.increment` must return. */
interface ThrottlerStorageRecord {
  totalHits: number;
  timeToExpire: number;
  isBlocked: boolean;
  timeToBlockExpire: number;
}

/** A RESP reply. */
type RespValue = string | number | null | Error | RespValue[];

/** The single operation the storage needs from a Redis client. */
export interface RedisEvalClient {
  /**
   * Runs a Lua script.
   *
   * @param script Lua source.
   * @param keys `KEYS` array.
   * @param args `ARGV` array.
   * @returns The script reply.
   */
  evalScript(script: string, keys: string[], args: string[]): Promise<unknown>;
}

/**
 * Atomic fixed-window counter with a block key.
 *
 * Returns `{hits, msUntilWindowReset, msUntilBlockEnds}`.
 */
const INCREMENT_SCRIPT = `
local hits = redis.call('INCR', KEYS[1])
if hits == 1 then redis.call('PEXPIRE', KEYS[1], ARGV[1]) end
local ttl = redis.call('PTTL', KEYS[1])
local blocked = redis.call('PTTL', KEYS[2])
if blocked <= 0 and hits > tonumber(ARGV[2]) then
  redis.call('SET', KEYS[2], '1', 'PX', ARGV[3])
  blocked = tonumber(ARGV[3])
end
if blocked < 0 then blocked = 0 end
return {hits, ttl, blocked}
`;

/**
 * `ThrottlerStorage` backed by Redis.
 */
export class RedisThrottlerStorage implements ThrottlerStorage {
  private readonly logger = new Logger(RedisThrottlerStorage.name);

  /**
   * @param client Redis client able to run a script.
   */
  constructor(private readonly client: RedisEvalClient) {}

  /**
   * Counts one hit.
   *
   * Fails open: when Redis is unreachable the request is let through and the
   * failure logged. Failing closed would turn a cache outage into a full API
   * outage; per-account lockout still bounds credential guessing meanwhile.
   *
   * @param key Tracker key generated by the guard.
   * @param ttl Window, in milliseconds.
   * @param limit Hits allowed per window.
   * @param blockDuration Block length once the limit is exceeded, in milliseconds.
   * @param throttlerName Named throttler.
   * @returns The throttler record.
   */
  async increment(
    key: string,
    ttl: number,
    limit: number,
    blockDuration: number,
    throttlerName: string,
  ): Promise<ThrottlerStorageRecord> {
    const base = `throttle:${throttlerName}:${key}`;
    try {
      const reply = await this.client.evalScript(
        INCREMENT_SCRIPT,
        [`${base}:hits`, `${base}:blocked`],
        [String(ttl), String(limit), String(blockDuration)],
      );
      const [hits, windowMs, blockMs] = (Array.isArray(reply) ? reply : []).map((v) => Number(v));
      return {
        totalHits: hits ?? 0,
        timeToExpire: Math.ceil(Math.max(0, windowMs ?? 0) / 1000),
        isBlocked: (blockMs ?? 0) > 0,
        timeToBlockExpire: Math.ceil(Math.max(0, blockMs ?? 0) / 1000),
      };
    } catch (error) {
      this.logger.warn(
        `Shared throttler storage unavailable; failing open: ${error instanceof Error ? error.message : String(error)}`,
      );
      return { totalHits: 0, timeToExpire: Math.ceil(ttl / 1000), isBlocked: false, timeToBlockExpire: 0 };
    }
  }
}

/**
 * Encodes a command as a RESP array of bulk strings.
 *
 * @param parts Command and arguments.
 * @returns The wire bytes.
 */
export function encodeCommand(parts: readonly string[]): Buffer {
  const chunks = [`*${parts.length}\r\n`];
  for (const part of parts) {
    chunks.push(`$${Buffer.byteLength(part)}\r\n${part}\r\n`);
  }
  return Buffer.from(chunks.join(''), 'utf8');
}

/**
 * Incremental RESP2 decoder.
 *
 * Buffers partial input and emits each complete top-level reply.
 */
export class RespReader {
  private buffer = Buffer.alloc(0);

  /**
   * Appends bytes and emits every complete reply.
   *
   * @param chunk Bytes received from the socket.
   * @param onReply Called once per complete reply.
   */
  feed(chunk: Buffer, onReply: (reply: RespValue) => void): void {
    this.buffer = Buffer.concat([this.buffer, chunk]);
    for (;;) {
      const parsed = this.parse(0);
      if (parsed === null) {
        return;
      }
      this.buffer = this.buffer.subarray(parsed.next);
      onReply(parsed.value);
    }
  }

  /**
   * Parses one value at `offset`.
   *
   * @param offset Byte offset.
   * @returns The value and the offset after it, or `null` when incomplete.
   */
  private parse(offset: number): { value: RespValue; next: number } | null {
    const lineEnd = this.buffer.indexOf('\r\n', offset);
    if (lineEnd === -1) {
      return null;
    }
    const type = String.fromCharCode(this.buffer[offset] ?? 0);
    const line = this.buffer.toString('utf8', offset + 1, lineEnd);
    const after = lineEnd + 2;
    switch (type) {
      case '+':
        return { value: line, next: after };
      case '-':
        return { value: new Error(line), next: after };
      case ':':
        return { value: Number(line), next: after };
      case '$': {
        const length = Number(line);
        if (length < 0) {
          return { value: null, next: after };
        }
        if (this.buffer.length < after + length + 2) {
          return null;
        }
        return { value: this.buffer.toString('utf8', after, after + length), next: after + length + 2 };
      }
      case '*': {
        const count = Number(line);
        if (count < 0) {
          return { value: null, next: after };
        }
        const items: RespValue[] = [];
        let cursor = after;
        for (let i = 0; i < count; i++) {
          const item = this.parse(cursor);
          if (item === null) {
            return null;
          }
          items.push(item.value);
          cursor = item.next;
        }
        return { value: items, next: cursor };
      }
      default:
        throw new Error(`Unexpected RESP type byte "${type}".`);
    }
  }
}

/**
 * Minimal Redis client: one lazily opened connection, commands pipelined in
 * order, `AUTH`/`SELECT` from the URL, `rediss://` over TLS.
 */
export class RespClient implements RedisEvalClient {
  private socket: Socket | null = null;
  private ready: Promise<void> | null = null;
  private readonly pending: { resolve: (v: RespValue) => void; reject: (e: Error) => void }[] = [];
  private reader = new RespReader();

  /**
   * @param url `redis://[user:password@]host[:port][/db]` or `rediss://…`.
   * @param timeoutMs Per-command timeout.
   */
  constructor(
    private readonly url: string,
    private readonly timeoutMs = 1_000,
  ) {}

  /** @inheritdoc */
  async evalScript(script: string, keys: string[], args: string[]): Promise<unknown> {
    return this.command(['EVAL', script, String(keys.length), ...keys, ...args]);
  }

  /** Closes the connection. */
  close(): void {
    this.socket?.destroy();
    this.reset(new Error('Redis client closed.'));
  }

  /**
   * Sends one command and resolves with its reply.
   *
   * @param parts Command and arguments.
   * @returns The reply.
   */
  async command(parts: readonly string[]): Promise<RespValue> {
    await this.connect();
    return this.send(parts);
  }

  private send(parts: readonly string[]): Promise<RespValue> {
    const socket = this.socket;
    if (socket === null) {
      return Promise.reject(new Error('Redis connection is not open.'));
    }
    return new Promise<RespValue>((resolve, reject) => {
      const timer = setTimeout(() => {
        // A reply that never comes desynchronises the pipeline; drop the socket.
        socket.destroy();
        this.reset(new Error('Redis command timed out.'));
      }, this.timeoutMs);
      timer.unref();
      this.pending.push({
        resolve: (value) => {
          clearTimeout(timer);
          if (value instanceof Error) {
            reject(value);
          } else {
            resolve(value);
          }
        },
        reject: (error) => {
          clearTimeout(timer);
          reject(error);
        },
      });
      // Keep the process alive only while a reply is owed, so an idle
      // connection never blocks a graceful shutdown.
      socket.ref();
      socket.write(encodeCommand(parts));
    });
  }

  private connect(): Promise<void> {
    if (this.ready !== null) {
      return this.ready;
    }
    const target = new URL(this.url);
    const port = Number(target.port || 6379);
    const host = target.hostname;
    this.ready = new Promise<void>((resolve, reject) => {
      const socket =
        target.protocol === 'rediss:'
          ? tlsConnect({ host, port, servername: host })
          : netConnect({ host, port });
      socket.setNoDelay(true);
      socket.unref();
      this.socket = socket;
      this.reader = new RespReader();
      socket.on('data', (chunk: Buffer) => {
        try {
          this.reader.feed(chunk, (reply) => this.pending.shift()?.resolve(reply));
          if (this.pending.length === 0) {
            socket.unref();
          }
        } catch (error) {
          socket.destroy();
          this.reset(error instanceof Error ? error : new Error(String(error)));
        }
      });
      socket.on('error', (error: Error) => {
        this.reset(error);
        reject(error);
      });
      socket.on('close', () => this.reset(new Error('Redis connection closed.')));
      socket.once(target.protocol === 'rediss:' ? 'secureConnect' : 'connect', () => {
        const handshake: Promise<RespValue>[] = [];
        if (target.password) {
          const password = decodeURIComponent(target.password);
          handshake.push(
            this.send(
              target.username ? ['AUTH', decodeURIComponent(target.username), password] : ['AUTH', password],
            ),
          );
        }
        const db = target.pathname.replace(/^\//, '');
        if (db) {
          handshake.push(this.send(['SELECT', db]));
        }
        Promise.all(handshake).then(() => resolve(), reject);
      });
    });
    return this.ready;
  }

  /**
   * Fails every in-flight command and forgets the connection, so the next
   * command reconnects.
   *
   * @param error Reason.
   */
  private reset(error: Error): void {
    this.socket = null;
    this.ready = null;
    for (const entry of this.pending.splice(0)) {
      entry.reject(error);
    }
  }
}
