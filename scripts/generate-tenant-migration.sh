#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Renders the tenant data plane datamodel into versioned SQL migrations.
#
# `prisma/schema.tenant.prisma` is the single source of truth for tenant data.
# Prisma Migrate can only manage one schema at a time, so the datamodel is
# rendered to SQL with `migrate diff` and applied per tenant schema at
# provisioning time.
#
# Usage:
#   npm run prisma:tenant:diff                      # create the next migration
#   npm run prisma:tenant:diff -- 0002_add_widgets  # create a named migration
#   npm run prisma:tenant:diff -- --check           # verify the tree is current
#
# The generated SQL is rewritten at apply time by `src/prisma/tenant-ddl.ts`,
# which strips `CREATE SCHEMA` and qualifies `CREATE TYPE` with the target schema.
# ---------------------------------------------------------------------------
set -euo pipefail

cd "$(dirname "$0")/.."

MIGRATIONS_DIR="prisma/tenant-migrations"
SCHEMA="prisma/schema.tenant.prisma"
LOCK_FILE="$MIGRATIONS_DIR/migration_lock.toml"

CHECK_ONLY=false
VERSION=""
for arg in "$@"; do
  case "$arg" in
    --check) CHECK_ONLY=true ;;
    [0-9]*) VERSION="$arg" ;;
  esac
done

mkdir -p "$MIGRATIONS_DIR"
[ -f "$LOCK_FILE" ] || printf '# Please do not edit this file manually\nprovider = "postgresql"\n' > "$LOCK_FILE"

# Next sequential version.
if [ -z "$VERSION" ]; then
  LAST=$(find "$MIGRATIONS_DIR" -mindepth 1 -maxdepth 1 -type d -name '[0-9]*' \
    -exec basename {} \; | sort -n | tail -1)
  NEXT=$(( ${LAST:-0} + 1 ))
  VERSION=$(printf '%04d_init_%s' "$NEXT" "$(date +%Y%m%d%H%M%S)")
fi

TARGET="$MIGRATIONS_DIR/$VERSION"
SQL_FILE="$TARGET/migration.sql"

# Render the full datamodel: every table, enum, index and constraint.
TMP_SQL="$(mktemp)"
trap 'rm -f "$TMP_SQL"' EXIT

npx prisma migrate diff \
  --from-empty \
  --to-schema "$SCHEMA" \
  --script \
  --output "$TMP_SQL"

# The rendered script contains an implicit CREATE SCHEMA for the template; the
# provisioner owns schema creation, so the statement is annotated here for the
# reviewer reading the migration file.
{
  printf -- '-- Tenant data plane migration %s\n' "$VERSION"
  printf -- '-- Generated by `npm run prisma:tenant:diff` from %s.\n' "$SCHEMA"
  printf -- '-- Do not edit by hand; edit the datamodel and regenerate.\n\n'
  sed 's|^CREATE SCHEMA IF NOT EXISTS "public";|-- schema creation is handled by the tenant provisioner|' "$TMP_SQL"
} > "$TMP_RENDERED_SQL"

if [ "$CHECK_ONLY" = true ]; then
  if [ -f "$SQL_FILE" ] && diff -q "$SQL_FILE" "$TMP_RENDERED_SQL" > /dev/null; then
    echo "Tenant migrations are up to date."
  else
    echo "Tenant migrations are OUT OF DATE. Run: npm run prisma:tenant:diff -- <version>_<name>" >&2
    exit 1
  fi
  exit 0
fi

if [ -f "$SQL_FILE" ]; then
  echo "Refusing to overwrite existing migration $VERSION." >&2
  exit 1
fi

mkdir -p "$TARGET"
mv "$TMP_RENDERED_SQL" "$SQL_FILE"

echo "Created tenant migration: $SQL_FILE"
echo "Apply it to existing tenants with: POST /tenants/:id/migrate"